/** The ambience loops, crossfaded by where the captain is and what is happening. */
export const LOOP_IDS = ['waves', 'timbers', 'rigging', 'surf', 'gulls', 'harbour', 'campfire'] as const;
export type LoopId = (typeof LOOP_IDS)[number];

export type SfxName = SoundId | LoopId;

export interface SoundSpec {
  /** What to ask ElevenLabs for. */
  prompt: string;
  /** How long to generate (ElevenLabs takes 0.5 to 30). */
  seconds: number;
  /** How many variants to generate. */
  takes: number;
  /** Gain, tuned by ear. */
  volume: number;
  /** World units from the camera's focus at which it fades to nothing; 0 is heard everywhere, centred. */
  reach: number;
  /** Most that may sound at once, per group, or per id when there is no group. */
  cap: number;
  group?: string;
  /** The random pitch shift, plus or minus this fraction. */
  pitch: number;
  loop?: true;
}

