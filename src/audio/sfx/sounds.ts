/** Match glob results (keys like ".../hull-hit-2.mp3") to sounds, each one's files in take order. Other files are ignored. */
export function filesFrom(paths: Record<string, string>): Map<SfxName, string[]> {
  const found = new Map<SfxName, { take: number; url: string }[]>();
  for (const [path, url] of Object.entries(paths)) {
    const m = /^(.+)-(\d+)\.mp3$/i.exec(path.split('/').pop()!);
    if (!m || !Object.hasOwn(SOUNDS, m[1])) continue;
    const name = m[1] as SfxName;
    const list = found.get(name) ?? [];
    list.push({ take: Number(m[2]), url });
    found.set(name, list);
  }
  const out = new Map<SfxName, string[]>();
  for (const [name, list] of found) out.set(name, list.sort((a, b) => a.take - b.take).map((f) => f.url));
  return out;
}
